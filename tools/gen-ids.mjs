// Writes the identifiers the behavior pack defines into packs/behavior/scripts/generated/ids.js,
// so the join self-check can compare them with what the game actually registered and name the
// definitions the game rejected. Run by `npm run check`.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname;
const BP = join(ROOT, 'packs/behavior');

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (name.endsWith('.json')) yield path;
  }
}
const ids = (/** @type {string} */ folder, /** @type {string} */ key) => {
  const out = [];
  for (const file of files(join(BP, folder))) {
    const id = JSON.parse(readFileSync(file, 'utf8'))?.[key]?.description?.identifier;
    if (typeof id === 'string' && id.startsWith('minepreggo:')) out.push(id);
  }
  return out.sort();
};
const out = join(BP, 'scripts/generated/ids.js');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by tools/gen-ids.mjs from the pack's JSON; do not edit.
export const ENTITY_IDS = ${JSON.stringify(ids('entities', 'minecraft:entity'))};
export const ITEM_IDS = ${JSON.stringify(ids('items', 'minecraft:item'))};
export const BLOCK_IDS = ${JSON.stringify(ids('blocks', 'minecraft:block'))};
`);
console.log(`ids: ${ids('entities', 'minecraft:entity').length} entities, ${ids('items', 'minecraft:item').length} items, ${ids('blocks', 'minecraft:block').length} blocks`);
